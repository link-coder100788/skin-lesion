"""Bundle the repo into self-contained Kaggle kernel scripts.

    python kaggle/build_kernel.py train   --user <kaggle-username>   # GPU training
    python kaggle/build_kernel.py explain --user <kaggle-username>   # notebooks 03-06 + app examples
    kaggle kernels push -p kaggle/build/<kind>

`train` runs `python -m src.train` with HAM10000 and Fitzpatrick17k attached.
`explain` takes the train kernel's output (cnn.pt, outputs.npz) as an input, rebuilds the
repo layout under /kaggle/working/proj, executes notebooks 03-06 and app/build_examples.py,
and leaves models/, results/, figures/, notebooks/*.ipynb and app/examples/ as output.
"""
import argparse
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HAM, FITZ, MASKS = ("kmader/skin-cancer-mnist-ham10000", "asosenge/fitzpatrick17k",
                    "tschandl/ham10000-lesion-segmentations")
SLUGS = {"train": "skin-lesion-triage-train", "explain": "skin-lesion-triage-explain",
         "sweep": "skin-lesion-triage-sweep"}
# Validation-only model sweep. All at 224 px so the SHAP/app pipeline is unchanged; the winner
# is picked on validation balanced accuracy, never on test.
SWEEP = {
    "b0_reg": "--backbone efficientnet_b0 --label-smoothing 0.1 --drop-path 0.2 --epochs 20",
    "b2_reg": "--backbone efficientnet_b2 --label-smoothing 0.1 --drop-path 0.2 --epochs 15",
    "b3_reg": "--backbone efficientnet_b3 --label-smoothing 0.1 --drop-path 0.2 --epochs 15",
}
# Pin the libraries whose versions affect saved artifacts (xgb.json, SHAP) to the local .venv.
PINS = "timm==1.0.31 shap==0.54.1 xgboost==3.4.1 grad-cam==1.5.7 jupytext==1.19.6"

HEADER = '''# Auto-generated by kaggle/build_kernel.py. Do not edit by hand.
import base64, io, os, subprocess, sys, tarfile
from pathlib import Path

BUNDLE = {bundle!r}  # base64 tar.gz of the repo files this kernel needs
work = Path("{workdir}")
work.mkdir(parents=True, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz").extractall(work, filter="data")

subprocess.run([sys.executable, "-m", "pip", "install", "-q", *{pins!r}.split()], check=False)
inp = Path("/kaggle/input")
ham = next(inp.rglob("HAM10000_metadata.csv")).parent
fitz = next(inp.rglob("fitzpatrick17k.csv")).parent
print("ham:", ham, "fitz:", fitz, flush=True)
'''

TRAIN = '''
subprocess.run([sys.executable, "-m", "src.train", "--ham", str(ham), "--fitz", str(fitz),
                "--split", "splits/split.csv", "--out", "/kaggle/working", {extra}],
               cwd=work, check=True)
'''

SWEEP_BODY = '''
for name, extra in {sweep!r}.items():
    print("=== config", name, extra, flush=True)
    r = subprocess.run([sys.executable, "-m", "src.train", "--ham", str(ham), "--fitz", str(fitz),
                        "--split", "splits/split.csv", "--out", f"/kaggle/working/{{name}}",
                        "--workers", "4", *extra.split()], cwd=work)
    print("=== config", name, "exit", r.returncode, flush=True)
'''

EXPLAIN = '''
import shutil
masks = next(inp.rglob("HAM10000_segmentations_lesion_tschandl"))
(work / "data").mkdir(exist_ok=True)
for name, target in [("ham", ham), ("fitz", fitz), ("masks", masks.parent)]:
    link = work / "data" / name
    if not link.exists():
        link.symlink_to(target)
(work / "models").mkdir(exist_ok=True)
MODEL_DIR = __MODEL_DIR__  # sub-folder of the source kernel's output holding the chosen model
for f in ("cnn.pt", "outputs.npz", "train_log.json"):
    src = next(p for p in inp.rglob(f) if "proj" not in str(p) and (not MODEL_DIR or p.parent.name == MODEL_DIR))
    shutil.copy(src, work / "models" / f)
for d in ("figures", "results", "app/examples"):
    (work / d).mkdir(parents=True, exist_ok=True)

try:
    for nb in ["03_train_cnn", "04_calibrate_fusion", "05_explain_shap", "06_eval_fairness"]:
        print("running", nb, flush=True)
        subprocess.run([sys.executable, "-m", "jupytext", "--to", "ipynb", "--set-kernel", "python3",
                        "--execute", f"{nb}.py"], cwd=work / "notebooks", check=True)
    subprocess.run([sys.executable, "app/build_examples.py"], cwd=work, check=True)
finally:
    # Never let the dataset symlinks end up in the kernel output.
    for name in ("ham", "fitz", "masks"):
        (work / "data" / name).unlink(missing_ok=True)
print("done", flush=True)
'''


def bundle(paths) -> str:
    import io
    import tarfile

    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz", compresslevel=9) as tar:
        for p in paths:
            tar.add(p, arcname=str(p.relative_to(ROOT)))
    return base64.b64encode(buf.getvalue()).decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("kind", choices=list(SLUGS))
    ap.add_argument("--user", required=True)
    ap.add_argument("--extra", default="", help="train only: extra args for src.train")
    ap.add_argument("--quick", action="store_true", help="explain only: QUICK=1 smoke run")
    ap.add_argument("--from-sweep", default="", help="explain only: use this sweep config's model")
    args = ap.parse_args()

    paths = sorted((ROOT / "src").glob("*.py")) + [ROOT / "splits/split.csv"]
    if args.kind == "sweep":
        body, workdir, datasets, kernels = (SWEEP_BODY.format(sweep=SWEEP), "/kaggle/working/code",
                                            [HAM, FITZ], [])
    elif args.kind == "train":
        extra = ", ".join(repr(a) for a in args.extra.split()) or "'--workers', '4'"
        body, workdir, datasets, kernels = TRAIN.format(extra=extra), "/kaggle/working/code", [HAM, FITZ], []
    else:
        paths += sorted((ROOT / "notebooks").glob("0[3-6]_*.py"))
        paths += [ROOT / "app/build_examples.py", ROOT / "results/artifact_flags.csv",
                  ROOT / "results/baseline_preds.npz"]
        body, workdir = EXPLAIN.replace("__MODEL_DIR__", repr(args.from_sweep)), "/kaggle/working/proj"
        if args.quick:
            body = '\nos.environ["QUICK"] = "1"\n' + body
        source = SLUGS["sweep"] if args.from_sweep else SLUGS["train"]
        datasets, kernels = [HAM, FITZ, MASKS], [f"{args.user}/{source}"]

    build = ROOT / "kaggle/build" / args.kind
    build.mkdir(parents=True, exist_ok=True)
    (build / "kernel.py").write_text(HEADER.format(bundle=bundle(paths), workdir=workdir, pins=PINS) + body)
    json.dump({
        "id": f"{args.user}/{SLUGS[args.kind]}",
        "title": SLUGS[args.kind],
        "code_file": "kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": datasets,
        "competition_sources": [],
        "kernel_sources": kernels,
    }, open(build / "kernel-metadata.json", "w"), indent=2)
    print("wrote", build)


if __name__ == "__main__":
    main()
