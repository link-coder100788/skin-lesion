"""Bundle src/ + the split file into one self-contained Kaggle kernel script.

    python kaggle/build_kernel.py --user <kaggle-username>
    kaggle kernels push -p kaggle/build

The kernel writes the embedded modules to disk, then runs `python -m src.train` on a GPU
with HAM10000 and Fitzpatrick17k attached as input datasets.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATASETS = ["kmader/skin-cancer-mnist-ham10000", "asosenge/fitzpatrick17k"]
SLUG = "skin-lesion-triage-train"

TEMPLATE = '''# Auto-generated by kaggle/build_kernel.py. Do not edit by hand.
import os, subprocess, sys
from pathlib import Path

FILES = {files!r}
work = Path("/kaggle/working/code")
for rel, text in FILES.items():
    p = work / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)

subprocess.run([sys.executable, "-m", "pip", "install", "-q", "timm"], check=False)

inp = Path("/kaggle/input")
ham = next(inp.rglob("HAM10000_metadata.csv")).parent
fitz = next(inp.rglob("fitzpatrick17k.csv")).parent
print("ham:", ham, "fitz:", fitz, flush=True)
subprocess.run([sys.executable, "-m", "src.train", "--ham", str(ham), "--fitz", str(fitz),
                "--split", "splits/split.csv", "--out", "/kaggle/working",
                {extra}], cwd=work, check=True)
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", required=True)
    ap.add_argument("--extra", default="", help="extra args for src.train, e.g. '--epochs 1'")
    args = ap.parse_args()

    files = {str(p.relative_to(ROOT)): p.read_text() for p in sorted((ROOT / "src").glob("*.py"))}
    files["splits/split.csv"] = (ROOT / "splits/split.csv").read_text()
    extra = ", ".join(repr(a) for a in args.extra.split()) or "'--workers', '4'"

    build = ROOT / "kaggle/build"
    build.mkdir(parents=True, exist_ok=True)
    (build / "kernel.py").write_text(TEMPLATE.format(files=files, extra=extra))
    json.dump({
        "id": f"{args.user}/{SLUG}",
        "title": SLUG,
        "code_file": "kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": DATASETS,
        "competition_sources": [],
        "kernel_sources": [],
    }, open(build / "kernel-metadata.json", "w"), indent=2)
    print("wrote", build)


if __name__ == "__main__":
    main()
